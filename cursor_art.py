# Builds the menu cursor (a weathered stone shard with moss) as a C array for the runtime.
import random, sys
from PIL import Image, ImageDraw, ImageFilter

S, K = 40, 8  # final size, supersample
random.seed(7)
big = S * K
# Arrow shard: tip at top-left, chipped edges like a broken castle block.
poly = [(2, 2), (27, 15), (19, 18), (25, 31), (19, 34), (13, 21), (6, 28)]
poly = [(x * K, y * K) for x, y in poly]
mask = Image.new("L", (big, big), 0)
ImageDraw.Draw(mask).polygon(poly, fill=255)

stone = Image.new("RGB", (big, big))
px = stone.load()
for y in range(big):
    for x in range(big):
        # Light from the upper left, like the game's sun on the shrine walls.
        shade = 188 - (x + y) * 62 // big
        px[x, y] = (shade, shade - 4, shade - 14)
grain = Image.effect_noise((big, big), 46).filter(ImageFilter.GaussianBlur(K * 0.35))
stone = Image.blend(stone, Image.merge("RGB", (grain, grain, grain)), 0.22)
d = ImageDraw.Draw(stone)
# Cracks.
for start in ((9, 9), (16, 14), (12, 20)):
    x, y = start[0] * K, start[1] * K
    for _ in range(9):
        nx, ny = x + random.randint(2, 9) * K // 4, y + random.randint(-3, 7) * K // 4
        d.line((x, y, nx, ny), fill=(70, 68, 62), width=K // 3)
        x, y = nx, ny
# Moss: clumps along the upper edge and in the cracks.
moss = Image.new("L", (big, big), 0)
md = ImageDraw.Draw(moss)
for cx, cy, n in ((6, 5, 70), (13, 9, 80), (21, 13, 60), (8, 22, 45), (17, 27, 40)):
    for _ in range(n):
        x = cx * K + random.gauss(0, K * 2.2)
        y = cy * K + random.gauss(0, K * 1.3)
        r = random.uniform(K * 0.3, K * 0.9)
        md.ellipse((x - r, y - r, x + r, y + r), fill=random.randint(150, 255))
moss = moss.filter(ImageFilter.GaussianBlur(K * 0.25))
green = Image.new("RGB", (big, big))
gp = green.load()
for y in range(big):
    for x in range(big):
        v = random.randint(-18, 18)
        gp[x, y] = (74 + v, 112 + v, 44 + v // 2)
stone = Image.composite(green, stone, moss)

# Dark outline so it reads on bright sky and on dark menus alike.
outline = mask.filter(ImageFilter.MaxFilter(K * 2 + 1))
out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
out.paste((24, 22, 20, 255), mask=outline)
out.paste(stone, mask=mask)
out = out.resize((S, S), Image.LANCZOS)
out.save(sys.argv[1] + ".png")
data = out.tobytes()
with open(sys.argv[1], "w", newline="\n") as f:
    f.write("// Generated by cursor_art.py: menu cursor, RGBA8.\n#pragma once\n\n")
    f.write(f"inline constexpr int SotcCursorSize = {S};\n")
    f.write("inline constexpr unsigned char SotcCursorPixels[] = {\n")
    for i in range(0, len(data), 20):
        f.write("    " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
